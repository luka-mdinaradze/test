#!/usr/bin/env python3
"""Generate pine/nq_frozen_candidates.pine from the frozen NQ configuration.

The script embeds the TRAINING time-of-day volatility profile and regime
thresholds, so TradingView computes the same statistics as the Python system:
gap-removed price, Wilder ATR on it, the seasonal EWMA volatility, z_mom and z_bb.

    python3 pine/generate_nq_pine.py
    python3 pine/check_pine.py pine/nq_frozen_candidates.pine

Known differences from the Python engine (documented in the script header):
TradingView fills on the chart timeframe (use Bar Magnifier for intrabar
resolution); ta.rma seeds ATR with an SMA; time and session exits fill at the
next bar's open.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from nqlab.config import MNQ, NQ_MARKET  # noqa: E402
from nqlab.live import regime_thresholds, train_profiles  # noqa: E402


def fmt_array(vals, per_line=8):
    vals = [f"{v:.5f}" for v in vals]
    rows = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return (",\n     ").join(rows)


def main():
    frozen = json.loads((ROOT / "results" / "frozen_config_NQ.json").read_text())
    cands = frozen["candidates"]
    tf = cands["A"]["tf"]
    if any(c["tf"] != tf for c in cands.values()):
        sys.exit("generator assumes all candidates share one timeframe")
    prof = train_profiles(NQ_MARKET, tf)
    th = regime_thresholds(NQ_MARKET, tf)
    a, b, c = cands["A"]["params"], cands["B"]["params"], cands["C"]
    n_long = max(20, int(round(10 * 1380 / tf)))
    route = c.get("route") or {"RTH": "NONE", "ETH": "NONE"}
    verdict = "NOT VALIDATED - NO TRADE" if not frozen["selected"] else f"VALIDATED: {frozen['selected']}"
    src = f'''//@version=5
// =============================================================================
// NQ / MNQ frozen research candidates — generated by pine/generate_nq_pine.py
// from results/frozen_config_NQ.json (commit {frozen["frozen_from_commit"][:10]}).
//
// SYSTEM VERDICT: {verdict}.
// No candidate passed the pre-registered validation (see NQ_RESEARCH.md). The
// default mode places NO orders. The research modes exist so the candidates can
// be inspected and PAPER-traded; their backtests here are not evidence of edge.
//
// Chart: CME_MINI:MNQ1! (or NQ1!) on the {tf}-minute timeframe, ETH session on,
// exchange time zone. Trigger agreement with the Python engine on 2023-2025 data
// (pine/verify_pine_math.py): A 99.2%, B 100%. Differences from the Python engine:
//   * fills are resolved on chart bars — enable Bar Magnifier (Premium) for
//     1-minute intrabar resolution; Python books the STOP when one minute
//     touches both stop and target
//   * ta.rma seeds the ATR with an SMA (warm-up only)
//   * time and session exits fill at the next bar's open
// =============================================================================
strategy("NQ frozen candidates ({verdict})", overlay=true, initial_capital=5000,
     commission_type=strategy.commission.cash_per_contract, commission_value={MNQ.commission_side},
     slippage={int(MNQ.slip_ticks_rth)}, pyramiding=0, calc_on_every_tick=false,
     default_qty_type=strategy.fixed, default_qty_value=1)

mode = input.string("NO TRADE (validated system)", "Mode",
     options=["NO TRADE (validated system)", "Research: A trend", "Research: B mean reversion", "Research: C session router"])
riskPct = input.float({100 * NQ_MARKET.account.risk_pct}, "Risk per trade (% of equity)", minval=0.1, maxval={100 * NQ_MARKET.account.max_risk_pct}, step=0.1)
maxQty = input.int({int(MNQ.max_qty)}, "Max contracts")

// ---- frozen parameters -----------------------------------------------------------
A_W = {a["w"]}
A_TAU = {a["tau"]}
A_K = {a["k"]}
A_RR = {a["rr"]}
A_HOLD = {int(2 * a["w"])}
B_W = {b["w"]}
B_Z = {b["z"]}
B_K = {b["k"]}
B_RR = {b["rr"]}
B_HOLD = {int(b["w"])}
C_RTH = "{route["RTH"]}"
C_ETH = "{route["ETH"]}"
LAM = 0.97
TF_MIN = {tf}
DAY_START = 1080
FLAT_D = {(NQ_MARKET.session.flatten_min - NQ_MARKET.session.day_start_min) % 1440}
NO_FIRST = {NQ_MARKET.session.no_entry_first_min}
NO_LAST = {NQ_MARKET.session.no_entry_last_min}
VOL_Q1 = {th.vol_q[0]:.6f}
VOL_Q2 = {th.vol_q[1]:.6f}
VOL_Q3 = {th.vol_q[2]:.6f}
var float[] PROF = array.from({fmt_array(prof.vol)})

// ---- session geometry (exchange time, ET) ----------------------------------------
mod = hour(time, "America/New_York") * 60 + minute(time, "America/New_York")
dmin = (mod - DAY_START + 1440) % 1440
newDay = dmin < nz(dmin[1], 0)
rth = mod >= 570 and mod < 960

// ---- gap-removed price: rolls, weekend gaps and the halt never enter a feature ----
// The Python engine drops the minutes after the flatten time, so on the one bar
// that straddles it (16:45-17:00 on 15m) it uses the last PRE-flatten minute.
// 1-minute intrabar data reproduces that; without it, the plain bar is used.
lowerC = request.security_lower_tf(syminfo.tickerid, "1", close)
lowerH = request.security_lower_tf(syminfo.tickerid, "1", high)
lowerL = request.security_lower_tf(syminfo.tickerid, "1", low)
straddle = dmin < FLAT_D and dmin + TF_MIN > FLAT_D
nPre = FLAT_D - dmin
cUse = close
hUse = high
lUse = low
if straddle and array.size(lowerC) >= nPre and nPre > 0
    cUse := array.get(lowerC, nPre - 1)
    hUse := array.max(array.slice(lowerH, 0, nPre))
    lUse := array.min(array.slice(lowerL, 0, nPre))
var float adj = 0.0
if newDay
    adj += open - close[1]
pc = cUse - adj
ph = hUse - adj
pl = lUse - adj
prevPc = nz(pc[1], pc)
tr = math.max(ph - pl, math.max(math.abs(ph - prevPc), math.abs(pl - prevPc)))
atr = ta.rma(tr, 14)

// ---- seasonal EWMA volatility (profile fitted on training data) ----------------------
slot = math.min(math.floor(dmin / TF_MIN), array.size(PROF) - 1)
sf = array.get(PROF, slot)
d = pc - prevPc
u2 = math.pow(d / sf, 2)
var float lev = na
prevLev = lev
lev := na(lev) ? (bar_index == 0 ? na : u2) : LAM * lev + (1 - LAM) * u2
sigNow = math.sqrt(prevLev) * sf
volReg = math.log(math.sqrt(lev)) - ta.median(math.log(math.sqrt(lev)), {n_long})
volLbl = na(volReg) ? "n/a" : volReg < VOL_Q1 ? "low" : volReg < VOL_Q2 ? "normal" : volReg < VOL_Q3 ? "high" : "extreme"

// ---- statistics -----------------------------------------------------------------------
zMom = math.sum(d, A_W) / math.sqrt(math.sum(sigNow * sigNow, A_W))
zBb = (pc - ta.sma(pc, B_W)) / ta.stdev(pc, B_W, false)

aLong = ta.crossover(zMom, A_TAU)
aShort = ta.crossunder(zMom, -A_TAU)
bLong = ta.crossunder(zBb, -B_Z)
bShort = ta.crossover(zBb, B_Z)
cUseA = (rth and C_RTH == "A") or (not rth and C_ETH == "A")
cUseB = (rth and C_RTH == "B") or (not rth and C_ETH == "B")

nextD = dmin + TF_MIN
entryWindow = nextD >= NO_FIRST and nextD < FLAT_D - NO_LAST
isA = mode == "Research: A trend" or (mode == "Research: C session router" and cUseA)
isB = mode == "Research: B mean reversion" or (mode == "Research: C session router" and cUseB)
goLong = entryWindow and ((isA and aLong) or (isB and bLong and not (isA and aShort)))
goShort = entryWindow and not goLong and ((isA and aShort) or (isB and bShort))
k = isA ? A_K : B_K
rr = isA ? A_RR : B_RR
hold = isA ? A_HOLD : B_HOLD

// ---- sizing: whole contracts inside the risk budget, never rounded up ----------------
stopPts = k * atr
slipPts = (rth ? {MNQ.slip_ticks_rth} : {MNQ.slip_ticks_eth}) * syminfo.mintick
perContract = (stopPts + slipPts) * syminfo.pointvalue + 2 * {MNQ.commission_side}
qty = math.min(math.floor(strategy.equity * riskPct / 100 / perContract), maxQty)
var int rejected = 0
var int holdBars = 0
var int entryBar = na

if mode != "NO TRADE (validated system)" and strategy.position_size == 0 and (goLong or goShort)
    if qty >= 1
        holdBars := hold
        entryBar := bar_index + 1
        strategy.entry(goLong ? "L" : "S", goLong ? strategy.long : strategy.short, qty=qty)
        strategy.exit("x", goLong ? "L" : "S", loss=stopPts / syminfo.mintick, profit=rr * stopPts / syminfo.mintick)
    else
        rejected += 1

// ---- time exit and session flatten --------------------------------------------------
if strategy.position_size != 0
    if bar_index - entryBar + 1 >= holdBars
        strategy.close_all(comment="time")
    // the NEXT bar contains the flatten time, and close_all fills at its open
    if dmin + 2 * TF_MIN > FLAT_D
        strategy.close_all(comment="flatten")

// ---- display -------------------------------------------------------------------------
var table info = table.new(position.top_right, 2, 7, border_width=1)
if barstate.islast
    table.cell(info, 0, 0, "System", text_size=size.small)
    table.cell(info, 1, 0, "{verdict}", text_color=color.red, text_size=size.small)
    table.cell(info, 0, 1, "Mode", text_size=size.small)
    table.cell(info, 1, 1, mode, text_size=size.small)
    table.cell(info, 0, 2, "z_mom(" + str.tostring(A_W) + ")", text_size=size.small)
    table.cell(info, 1, 2, str.tostring(zMom, "#.##"), text_size=size.small)
    table.cell(info, 0, 3, "z_bb(" + str.tostring(B_W) + ")", text_size=size.small)
    table.cell(info, 1, 3, str.tostring(zBb, "#.##"), text_size=size.small)
    table.cell(info, 0, 4, "Regime", text_size=size.small)
    table.cell(info, 1, 4, (rth ? "RTH" : "ETH") + " / vol " + volLbl, text_size=size.small)
    table.cell(info, 0, 5, "1 contract risk", text_size=size.small)
    table.cell(info, 1, 5, "$" + str.tostring(perContract, "#.##") + " vs budget $" + str.tostring(strategy.equity * riskPct / 100, "#.##"), text_size=size.small)
    table.cell(info, 0, 6, "Rejected (size)", text_size=size.small)
    table.cell(info, 1, 6, str.tostring(rejected), text_size=size.small)
plotshape(isA and aLong and entryWindow, "A long trigger", shape.triangleup, location.belowbar, color.new(color.teal, 40), size=size.tiny)
plotshape(isA and aShort and entryWindow, "A short trigger", shape.triangledown, location.abovebar, color.new(color.maroon, 40), size=size.tiny)
plotshape(isB and bLong and entryWindow, "B long trigger", shape.circle, location.belowbar, color.new(color.teal, 40), size=size.tiny)
plotshape(isB and bShort and entryWindow, "B short trigger", shape.circle, location.abovebar, color.new(color.maroon, 40), size=size.tiny)
'''
    out = ROOT / "pine" / "nq_frozen_candidates.pine"
    out.write_text(src)
    print(f"wrote {out} ({len(src.splitlines())} lines)")


if __name__ == "__main__":
    main()
